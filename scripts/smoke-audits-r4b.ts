import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { prisma } from "../src/lib/db";
import { createAnnualPlan, addPlanEntry, updatePlanEntry, retirePlanEntry, getAnnualPlan, getPlanOptions, listAnnualPlans } from "../src/modules/audits/plans";
import { saveAudit, auditDefaults } from "../src/modules/audits/service";
import { getAuditList } from "../src/modules/audits/queries";

async function main() {
  if (process.env.APP_ENV !== "test") throw new Error("R4B smoke solo en APP_ENV=test con PostgreSQL aislado.");
  const marker = "R4B-DB-" + randomUUID();
  const year = 2092;
  const actor = "Verificación automatizada R4B";
  const department = await prisma.department.findUniqueOrThrow({where:{code:"GC-00"}});
  const legacy = await prisma.audit.findFirst({where:{planningStatus:"UNCLASSIFIED",planEntryId:null},select:{id:true,planningStatus:true,planEntryId:true,qmsRecordId:true}});
  const initialAuditCount = await prisma.audit.count();
  const internal = await createAnnualPlan({year,auditType:"INTERNAL",title:"Plan interno "+marker,notes:"Datos ficticios",actor});
  const external = await createAnnualPlan({year,auditType:"EXTERNAL",title:"Plan externo "+marker,notes:"Datos ficticios",actor});
  assert.notEqual(internal.id,external.id);
  await assert.rejects(createAnnualPlan({year,auditType:"INTERNAL",title:"Duplicado",notes:"",actor}),/Ya existe/);
  let plan = await getAnnualPlan(internal.id);
  assert(plan && plan.changes.some(c=>c.event==="PLAN_CREATED"));
  assert((await listAnnualPlans()).some(p=>p.id===internal.id));
  const makeInput = (subject:string) => ({subject,targetName:"Área o entidad ficticia",departmentId:department.id,plannedDate:"2092-04-15",notes:"",actor,reason:""});
  const first = (await addPlanEntry(internal.id,makeInput(marker+" auditoría 1"))).entry;
  const free = (await addPlanEntry(internal.id,makeInput(marker+" auditoría 2"))).entry;
  const supplier = (await addPlanEntry(external.id,{...makeInput(marker+" proveedor"),departmentId:""})).entry;
  await assert.rejects(addPlanEntry(internal.id,{...makeInput("Departamento inexistente"),departmentId:randomUUID()}),/departamento/i);
  await assert.rejects(updatePlanEntry(internal.id,free.id,{...makeInput("Sin motivo"),reason:""}),/motivo/i);
  await updatePlanEntry(internal.id,free.id,{...makeInput(marker+" auditoría modificada"),plannedDate:"2092-05-07",reason:"Reprogramación documentada"});
  assert.equal((await prisma.auditPlanEntry.findUniqueOrThrow({where:{id:free.id}})).plannedDate?.toISOString().slice(0,10),"2092-05-07");
  const base = {actor,status:"DRAFT" as const,auditType:"INTERNAL" as const,scenario:"INTERNAL_COVEX" as const,title:marker+" expediente",scope:"Alcance ficticio",plannedDate:"2092-04-15",departmentIds:[department.id],codingDepartmentId:department.id,participants:[{displayName:"Auditor ficticio",role:"AUDITOR" as const,sortOrder:0}],businessCode:"",planningStatus:"PLANNED" as const,planEntryId:first.id};
  const audit = await saveAudit(base);
  assert.equal(audit.planningStatus,"PLANNED");
  assert.equal(audit.planEntryId,first.id);
  assert.equal((await getAnnualPlan(internal.id))?.entries.find(e=>e.id===first.id)?.audit?.id,audit.id);
  assert.equal((await getAuditList({planning:"PLANNED",planId:internal.id,q:marker})).total,1);
  assert.equal((await getAuditList({planning:"PLANNED",planId:external.id,q:marker})).total,0);
  await assert.rejects(saveAudit({...base,title:marker+" segundo expediente"}),/otra auditoría vinculada|Unique constraint|P2002/i);
  await assert.rejects(saveAudit({...base,planEntryId:supplier.id,title:"Tipo incorrecto"}),/tipo de auditoría/i);
  await assert.rejects(retirePlanEntry(internal.id,first.id,actor,"No se puede retirar con expediente"),/vinculada/i);
  await assert.rejects(saveAudit({...auditDefaults(audit),planningStatus:"OUT_OF_PLAN",planEntryId:"",outsidePlanReason:"Extraordinaria",changeReason:""},audit.id),/motivo|Justifica/i);
  const changed = await saveAudit({...auditDefaults(audit),planningStatus:"OUT_OF_PLAN",planEntryId:"",outsidePlanReason:"Auditoría extraordinaria",changeReason:"Reclasificación fundamentada"},audit.id);
  assert.equal(changed.planningStatus,"OUT_OF_PLAN");
  assert.equal(changed.planEntryId,null);
  assert.equal((await getAuditList({planning:"OUT_OF_PLAN",q:marker})).total,1);
  assert.equal((await getAuditList({planning:"PLANNED",planId:internal.id,q:marker})).total,0);
  const relinked = await saveAudit({...auditDefaults(changed),planningStatus:"PLANNED",planEntryId:first.id,outsidePlanReason:"",changeReason:"Corrección documentada"},audit.id);
  assert.equal(relinked.planEntryId,first.id);
  await retirePlanEntry(internal.id,free.id,actor,"Cancelación ficticia sin expediente");
  await assert.rejects(retirePlanEntry(internal.id,free.id,actor,"Duplicado"),/retirada/i);
  await assert.rejects(saveAudit({...base,planEntryId:free.id,title:"Retirada"}),/no está disponible/i);
  plan = await getAnnualPlan(internal.id);
  assert(plan && plan.entries.find(e=>e.id===free.id)?.isActive===false);
  assert(plan.changes.some(e=>e.event==="ENTRY_RETIRED"&&e.reason.includes("Cancelación")));
  assert(plan.changes.some(e=>e.event==="ENTRY_UPDATED"&&e.reason==="Reprogramación documentada"));
  assert(plan.changes.some(e=>e.event==="AUDIT_CLASSIFICATION"));
  assert((await getPlanOptions()).find(p=>p.id===internal.id)?.entries.every(e=>e.id!==free.id));
  assert((await prisma.audit.findUniqueOrThrow({where:{id:audit.id}})).qmsRecordId);
  assert.equal(await prisma.audit.count(),initialAuditCount+1);
  if (legacy) {
    const untouched = await prisma.audit.findUniqueOrThrow({where:{id:legacy.id}});
    assert.equal(untouched.planningStatus,"UNCLASSIFIED");
    assert.equal(untouched.planEntryId,null);
    assert.equal(untouched.qmsRecordId,legacy.qmsRecordId);
  }
  assert((await prisma.auditPlanEntry.findUniqueOrThrow({where:{id:supplier.id}})).isActive);
  console.log("R4B PostgreSQL OK: planes internos/externos, unicidad, modificaciones e historial, vinculación, fuera de plan, filtros, retirada y preservación histórica.");
}
main().catch(e=>{console.error("R4B PostgreSQL FAIL:",e);process.exitCode=1}).finally(async()=>{await prisma.$disconnect()});
