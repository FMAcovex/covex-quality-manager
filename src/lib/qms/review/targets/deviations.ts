export function deviationImmediateActionReviewTarget(
  targetEntityId: string,
  valueSnapshot: ReviewSnapshotValue,
): ReviewTargetInstance {
  const stableId = stableReviewAnchorPart(targetEntityId);
  return {
    key: `deviation.actions.immediate-action.${targetEntityId}.description`,
    module: QmsRecordType.DEVIATION,
    targetKind: ReviewTargetKind.ITEM,
    tabKey: "actions",
    sectionKey: "immediate-actions",
    fieldPath: "description",
    label: "Acción inmediata",
    anchorId: `review-deviation-immediate-action-${stableId}`,
    targetEntityType: "DeviationImmediateAction",
    targetEntityId,
    valueSnapshot,
  };
}

