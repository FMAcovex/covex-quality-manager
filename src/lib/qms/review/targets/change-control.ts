export function changeControlTaskReviewTarget(targetEntityId: string, valueSnapshot: ReviewSnapshotValue): ReviewTargetInstance {
  return {
    key: `change-control.dictamen.task.${targetEntityId}`,
    module: QmsRecordType.CHANGE_CONTROL, targetKind: ReviewTargetKind.ITEM,
    tabKey: "dictamen", sectionKey: "execution-plan", fieldPath: "description",
    label: "Acción del Plan de ejecución", anchorId: `review-change-control-task-${stableReviewAnchorPart(targetEntityId)}`,
    targetEntityType: "ChangeControlTask", targetEntityId, valueSnapshot,
  };
}

export function changeControlFollowupReviewTarget(targetEntityId: string, valueSnapshot: ReviewSnapshotValue, sequenceNumber?: number): ReviewTargetInstance {
  return {
    key: `change-control.followups.item.${targetEntityId}`,
    module: QmsRecordType.CHANGE_CONTROL, targetKind: ReviewTargetKind.ITEM,
    tabKey: "followups", sectionKey: "followups", fieldPath: null,
    label: sequenceNumber === undefined ? "Seguimiento" : `Seguimiento ${String(sequenceNumber).padStart(2, "0")}${sequenceNumber === 0 ? " · Apertura" : ""}`,
    anchorId: `review-change-control-followup-${stableReviewAnchorPart(targetEntityId)}`,
    targetEntityType: "ChangeControlFollowup", targetEntityId, valueSnapshot,
  };
}
