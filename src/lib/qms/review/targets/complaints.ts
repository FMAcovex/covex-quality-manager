export function complaintCapaPlanReviewTarget(
  targetEntityId: string,
  valueSnapshot: ReviewSnapshotValue,
): ReviewTargetInstance {
  const stableId = stableReviewAnchorPart(targetEntityId);
  return {
    key: `complaint.part-i.capa-plan.${targetEntityId}.description`,
    module: QmsRecordType.COMPLAINT,
    targetKind: ReviewTargetKind.ITEM,
    tabKey: "part-i",
    sectionKey: "derived-actions",
    fieldPath: "description",
    label: "Descripción de propuesta CAPA",
    anchorId: `review-complaint-capa-plan-${stableId}`,
    targetEntityType: "ComplaintCapaPlan",
    targetEntityId,
    valueSnapshot,
  };
}
